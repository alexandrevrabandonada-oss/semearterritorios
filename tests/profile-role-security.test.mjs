import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
create schema auth; create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true),'')::uuid $$;
create table public.profiles(id uuid primary key, full_name text, role text, created_at timestamptz default now(), updated_at timestamptz default now());
alter table public.profiles enable row level security;
grant select,insert,update,truncate on public.profiles to anon,authenticated;
grant insert(role),update(role) on public.profiles to authenticated;
create policy authenticated_read on public.profiles for select to authenticated using(true);
create policy authorized_update on public.profiles for update to authenticated using(true) with check(true);
insert into public.profiles(id,full_name,role) values ('00000000-0000-4000-8000-000000000001','Synthetic','admin'),('00000000-0000-4000-8000-000000000002','Synthetic','equipe');`);
await db.exec(readFileSync('supabase/migrations/20261117000613_restrict_profile_role_changes.sql','utf8'));
await db.exec('set role authenticated');
await assert.rejects(db.exec(`update public.profiles set role='admin' where id='00000000-0000-4000-8000-000000000002'`));
await assert.rejects(db.exec(`insert into public.profiles(id,role) values ('00000000-0000-4000-8000-000000000003','admin')`));
await db.exec(`update public.profiles set full_name='Synthetic updated' where id='00000000-0000-4000-8000-000000000002'`);
await db.exec('reset role');
assert.equal((await db.query(`select role from profiles where id='00000000-0000-4000-8000-000000000002'`)).rows[0].role,'equipe');
await db.exec(`update public.profiles set role='coordenacao' where id='00000000-0000-4000-8000-000000000002'`);
console.log('PASS authenticated role escalation blocked; safe update and controlled DBA update preserved');
await db.close();
